const GITHUB_USERNAME = process.env.GITHUB_USERNAME || process.env.VITE_GITHUB_USERNAME || 'baej12';
const GITHUB_TOKEN = process.env.GITHUB_TOKEN || process.env.GH_TOKEN || '';
const MAX_REPOS = 100;
const MAX_LANGUAGES = 4;
const MAX_RECENT_COMMITS = 3;
const CONCURRENCY = 4;

const defaultHeaders = {
  Accept: 'application/vnd.github+json',
  'X-GitHub-Api-Version': '2022-11-28',
  ...(GITHUB_TOKEN ? { Authorization: `Bearer ${GITHUB_TOKEN}` } : {}),
};

const githubApiGet = async (url, params = undefined) => {
  const target = new URL(url, 'https://api.github.com');
  if (params) {
    Object.entries(params).forEach(([key, value]) => {
      if (value !== undefined && value !== null) {
        target.searchParams.set(key, String(value));
      }
    });
  }

  const response = await fetch(target, { headers: defaultHeaders });
  if (!response.ok) {
    const body = await response.text();
    throw new Error(`GitHub API ${response.status} for ${target.pathname}: ${body.slice(0, 300)}`);
  }

  return response.json();
};

const runWithConcurrency = async (items, limit, worker) => {
  const results = new Array(items.length);
  let nextIndex = 0;

  const consume = async () => {
    while (nextIndex < items.length) {
      const current = nextIndex;
      nextIndex += 1;
      results[current] = await worker(items[current]);
    }
  };

  const workers = Array.from({ length: Math.min(limit, items.length) }, () => consume());
  await Promise.all(workers);
  return results;
};

const safeFirstCommitLine = (message) => (message || '').split('\n')[0].trim();

const normalizeDate = (value) => {
  if (!value) return '';
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return '';
  return date.toISOString().slice(0, 10);
};

const toRepoSummary = async (repo) => {
  const languagesPromise = repo.languages_url
    ? githubApiGet(repo.languages_url)
    : Promise.resolve({});

  const commitsPromise = githubApiGet(`/repos/${GITHUB_USERNAME}/${repo.name}/commits`, {
    sha: repo.default_branch || 'main',
    per_page: MAX_RECENT_COMMITS,
  });

  const [languagesData, commits] = await Promise.all([languagesPromise, commitsPromise]);

  const languages = Object.entries(languagesData)
    .sort((a, b) => b[1] - a[1])
    .map(([name]) => name)
    .slice(0, MAX_LANGUAGES);

  const commitDetails = await Promise.all(
    commits.map((commit) =>
      githubApiGet(`/repos/${GITHUB_USERNAME}/${repo.name}/commits/${commit.sha}`)
        .catch(() => null)
    )
  );

  const recentCommits = commits.map((commit, index) => {
    const detail = commitDetails[index];
    return {
      sha: String(commit.sha || '').slice(0, 7),
      message: safeFirstCommitLine(commit?.commit?.message),
      date: normalizeDate(commit?.commit?.author?.date),
      additions: detail?.stats?.additions || 0,
      deletions: detail?.stats?.deletions || 0,
      changedFiles: Array.isArray(detail?.files) ? detail.files.length : 0,
    };
  });

  return {
    name: repo.name,
    htmlUrl: repo.html_url,
    description: repo.description || null,
    defaultBranch: repo.default_branch || 'main',
    updatedAt: repo.updated_at || null,
    primaryLanguage: repo.language || null,
    languages,
    recentCommits,
  };
};

const writeGeneratedFile = async (repoSummaries) => {
  const outPath = new URL('../src/data/repoStats.generated.ts', import.meta.url);
  const source = [
    '// This file is auto-generated by scripts/generate-repo-stats.mjs',
    '// Do not edit manually.',
    '',
    'export interface GeneratedRepoCommitStats {',
    '  sha: string;',
    '  message: string;',
    '  date: string;',
    '  additions: number;',
    '  deletions: number;',
    '  changedFiles: number;',
    '}',
    '',
    'export interface GeneratedRepoStats {',
    '  name: string;',
    '  htmlUrl: string;',
    '  description: string | null;',
    '  defaultBranch: string;',
    '  updatedAt: string | null;',
    '  primaryLanguage: string | null;',
    '  languages: string[];',
    '  recentCommits: GeneratedRepoCommitStats[];',
    '}',
    '',
    `export const generatedRepoStats: GeneratedRepoStats[] = ${JSON.stringify(repoSummaries, null, 2)};`,
    '',
    'export default generatedRepoStats;',
    '',
  ].join('\n');

  const fs = await import('node:fs/promises');
  await fs.writeFile(outPath, source, 'utf8');
};

const main = async () => {
  console.log('Fetching repositories from GitHub...');

  const repos = await githubApiGet(`/users/${GITHUB_USERNAME}/repos`, {
    sort: 'updated',
    direction: 'desc',
    per_page: MAX_REPOS,
  });

  const sortedRepos = [...repos].sort((a, b) => {
    const aTime = a.updated_at ? Date.parse(a.updated_at) : 0;
    const bTime = b.updated_at ? Date.parse(b.updated_at) : 0;
    return bTime - aTime;
  });

  const repoSummaries = await runWithConcurrency(sortedRepos, CONCURRENCY, toRepoSummary);

  await writeGeneratedFile(repoSummaries);
  console.log(`Generated stats for ${repoSummaries.length} repositories.`);
};

main().catch((error) => {
  console.error(error.message || error);
  process.exitCode = 1;
});
